/// Real-time position in the day/night cycle. Advances every frame while in
/// a world (`advance_clock`) and is reset from - then kept in sync with -
/// the active world's save data (`world.rs`'s `enter_world`/`write_save`).
#[derive(Resource)]
pub struct DayNightClock {
    /// Seconds into the current `[0, CYCLE_SECONDS)` cycle. `0` is dawn:
    /// the sun exactly on the eastern horizon, about to rise.
    pub elapsed: f32,
    /// How many full day/night cycles have elapsed since the world began -
    /// increments the instant `elapsed` wraps back to `0` (`advance_clock`).
    /// Only ever consulted through [`Self::moon_phase`]; nothing else reads
    /// it directly.
    pub day_count: u32,
}

impl Default for DayNightClock {
    fn default() -> Self {
        Self { elapsed: 0.0, day_count: 0 }
    }
}

impl DayNightClock {
    pub fn is_day(&self) -> bool {
        self.elapsed < DAY_SECONDS
    }

    /// 0..1 progress through whichever of day/night is currently active -
    /// `0` right at rise, `1` right at set.
    fn phase_progress(&self) -> f32 {
        if self.is_day() {
            self.elapsed / DAY_SECONDS
        } else {
            (self.elapsed - DAY_SECONDS) / NIGHT_SECONDS
        }
    }

    /// The active body's angle above the eastern horizon: `0` at rise,
    /// `PI` at set, `PI/2` at zenith - see [`celestial_offset`].
    fn phase_angle(&self) -> f32 {
        self.phase_progress() * PI
    }

    /// `0` at rise/set, `1` at zenith. Doubles as both a fade-near-the-
    /// horizon factor and the world's daylight brightness (see
    /// [`Self::daylight`]) - a plain sine naturally eases both smoothly
    /// through sunrise/sunset with no separate interpolation needed.
    fn phase_height(&self) -> f32 {
        self.phase_angle().sin().max(0.0)
    }

    /// How daylit the world is right now: `0` at the depths of night up to
    /// `1` at high noon, driven entirely by the sun's height so sunrise and
    /// sunset ease naturally. Pinned to `0` for the whole night phase - the
    /// moon lights nothing, it just lets you see it's up.
    pub fn daylight(&self) -> f32 {
        if self.is_day() {
            self.phase_height()
        } else {
            0.0
        }
    }

    /// Which of the 8 moon phases is showing tonight: `0` = new, `2` =
    /// first quarter, `4` = full, `6` = last quarter, with a waxing
    /// crescent/gibbous at `1`/`3` and waning crescent/gibbous at `7`/`5` -
    /// advances by one every full day/night cycle (`advance_clock`), the
    /// same one-phase-per-day convention Minecraft uses. See [`moon_lit`]
    /// for how a phase index becomes a lit/dark shape.
    pub fn moon_phase(&self) -> u8 {
        (self.day_count % 8) as u8
    }

    /// How many full [`DAYS_PER_MONTH`]-day months have elapsed - a "month"
    /// is defined to exactly match the moon's own phase cycle, so a full
    /// moon (`moon_phase() == 4`) always lands in the middle of every month.
    fn month(&self) -> u32 {
        self.day_count / DAYS_PER_MONTH
    }

    /// `month()`, wrapped to a `[0, MONTHS_PER_YEAR)` position within the
    /// current year - what [`Self::season`] and [`Self::moon_event`] key off.
    fn month_of_year(&self) -> u32 {
        self.month() % MONTHS_PER_YEAR
    }

    /// The current calendar season - a pure calendar concept with no other
    /// gameplay effect yet (see the module docs): it exists solely so
    /// [`MoonEventDef::excluded_seasons`] is a real, checkable rule instead
    /// of a permanent no-op.
    pub fn season(&self) -> Season {
        season_of_month(self.month_of_year())
    }

    /// Tonight's special moon coloring, if any - see [`MOON_EVENTS`] for
    /// the full rules (frequency, excluded seasons, whether it needs a
    /// full moon). `world_seed` is `WorldSettings::seed`, threaded in
    /// rather than stored on the clock itself, since nothing else about
    /// the clock needs to know which world it belongs to. Purely cosmetic
    /// for now (see the module docs) - `update_sky` is the only consumer,
    /// tinting whichever phase material is currently shown.
    pub fn moon_event(&self, world_seed: u32) -> Option<MoonEvent> {
        let year = self.month() / MONTHS_PER_YEAR;
        let event = year_schedule(world_seed, year)[self.month_of_year() as usize]?;
        let def = MOON_EVENTS.iter().find(|d| d.event == event)?;
        if def.requires_full_moon && self.moon_phase() != 4 {
            return None;
        }
        Some(event)
    }
}

fn season_of_month(month_of_year: u32) -> Season {
    match month_of_year {
        0..=2 => Season::Spring,
        3..=5 => Season::Summer,
        6..=8 => Season::Autumn,
        _ => Season::Winter, // 9..=11
    }
}

/// True if `month` sits immediately before or after a month that already
/// has an event this year, *or* is month `0` and `previous_december_claimed`.
/// That second case is the one piece of cross-year information
/// [`year_schedule`] threads in so the gap rule holds across a year
/// boundary too (no claimed December immediately followed by a claimed
/// January), not just within one year.
fn touches_a_claimed_month(
    month: u32,
    schedule: &[Option<MoonEvent>; MONTHS_PER_YEAR as usize],
    previous_december_claimed: bool,
) -> bool {
    let before_claimed = if month == 0 {
        previous_december_claimed
    } else {
        schedule[month as usize - 1].is_some()
    };
    before_claimed || (month + 1 < MONTHS_PER_YEAR && schedule[month as usize + 1].is_some())
}

/// Deterministically (but pseudo-randomly, re-rolled fresh every year)
/// assigns one year's [`MOON_EVENTS`] occurrences to specific months -
/// `[i]` is which event (if any) month `i` hosts. Seeded from the world's
/// seed plus the year number, so it's reproducible for a given world and
/// year (a reload must show the same schedule) but differs world to world
/// and year to year - the same seeded-not-truly-random determinism every
/// other procedural piece of this engine (terrain, block texture jitter)
/// already follows.
///
/// Events are drawn in [`MOON_EVENTS`]'s table order, each occurrence
/// picking fresh from whatever's currently eligible: not yet claimed this
/// year, not in one of the event's own excluded seasons, and (if
/// `requires_gap_month`) not touching an already-claimed month, including
/// the previous year's December via `previous_december_claimed` -
/// recomputed after every single pick, not just once per event, so an
/// event drawing more than one occurrence (red draws two) can't land its
/// own two months next to each other either. Table order acts as a
/// priority (earlier entries get first pick of any months two entries
/// could both use - e.g. blue's non-winter pool and green's non-spring
/// pool genuinely overlap in summer/autumn), but claiming as each month is
/// picked is what actually guarantees no two events ever collide or end up
/// adjacent, regardless of how much their pools overlap. If an event's
/// eligible pool ever runs dry before `per_year` is satisfied (possible in
/// principle with a much more restrictive custom table than the one
/// below), it simply gets fewer occurrences that year rather than panicking.
fn year_schedule_one_year(
    world_seed: u32,
    year: u32,
    previous_december_claimed: bool,
) -> [Option<MoonEvent>; MONTHS_PER_YEAR as usize] {
    let mut schedule = [None; MONTHS_PER_YEAR as usize];
    let base = hash_str(&format!("moon-events-{world_seed}-{year}"));
    for (i, def) in MOON_EVENTS.iter().enumerate() {
        // A large prime offset per event index gives each its own
        // independent pseudo-random stream from the same year's base seed.
        let mut rng = mulberry32(base.wrapping_add(i as u32 * 104_729));
        for _ in 0..def.per_year {
            let pool: Vec<u32> = (0..MONTHS_PER_YEAR)
                .filter(|&m| {
                    schedule[m as usize].is_none()
                        && !def.excluded_seasons.contains(&season_of_month(m))
                        && (!def.requires_gap_month
                            || !touches_a_claimed_month(m, &schedule, previous_december_claimed))
                })
                .collect();
            if pool.is_empty() {
                break;
            }
            let idx = ((rng() * pool.len() as f32) as usize).min(pool.len() - 1);
            schedule[pool[idx] as usize] = Some(def.event);
        }
    }
    schedule
}

/// [`year_schedule_one_year`], but carries the gap rule across year
/// boundaries too: a claimed December must block the following January
/// exactly as it would block any other adjacent month, which needs to know
/// whether *last* year's December was claimed - which itself depends on
/// the year before that, all the way back to year `0`. Walking forward
/// from year `0` and keeping only that one rolling fact (never the full
/// history of every prior year) keeps this cheap regardless of how large
/// `year` gets over a long-lived save: `O(year)` tiny 12-month passes, not
/// `O(year)` worth of state kept around. `update_sky` calls this fresh
/// every frame like everything else in this module - even a save many
/// real-world years old is nowhere near enough played time (at 30 minutes
/// per in-game day, one in-game year is 48 real hours) to make that loop
/// noticeable.
fn year_schedule(world_seed: u32, target_year: u32) -> [Option<MoonEvent>; MONTHS_PER_YEAR as usize] {
    let mut schedule = [None; MONTHS_PER_YEAR as usize];
    let mut previous_december_claimed = false;
    for year in 0..=target_year {
        schedule = year_schedule_one_year(world_seed, year, previous_december_claimed);
        previous_december_claimed = schedule[MONTHS_PER_YEAR as usize - 1].is_some();
    }
    schedule
}

