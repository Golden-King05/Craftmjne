//! Day/night cycle: a real-time clock (20-minute days, 10-minute nights,
//! see [`DAY_SECONDS`]/[`NIGHT_SECONDS`]) driving a sun and a moon that rise
//! due east and set due west - this engine's established compass mapping
//! (`blocks.rs`'s face-order doc: +X east, -X west, -Z north, +Z south) -
//! arcing straight overhead through the zenith. Only one is ever up at a
//! time: the sun for the whole day phase, the moon for the whole night
//! phase, each completing its entire rise-to-set arc within its own phase's
//! duration.
//!
//! Both are flat, always-camera-facing quads (billboards) orbiting the
//! camera at a fixed radius - the same "attached to the sky, not the world"
//! trick real-time-strategy/voxel games have used forever, cheap because it
//! needs no new geometry per chunk and no dynamic light source at all.
//!
//! This is a fully unlit renderer (see `render.rs`'s module docs): there's
//! no real light to dim at night, so `update_sky` instead writes a single
//! global brightness multiplier (`render::ChunkMaterialParams::sky_light`)
//! into both chunk materials every frame, plus the sky/fog color - cheap
//! (two tiny uniform writes, no remeshing) despite touching the whole
//! world's apparent lighting at once.
//!
//! Sun/moon textures are procedurally generated by default (this module),
//! exactly like block textures (`atlas.rs`) - drop a `textures/sky/sun.png`
//! or `textures/sky/moon.png` to override one with real art instead; no
//! code changes, no recompile. Unlike the block atlas there's no shared
//! resolution or tile-packing to keep in sync, since each is one standalone
//! sprite - any square PNG is used at its own native size.
//!
//! The moon additionally cycles through 8 phases (new, waxing crescent,
//! first quarter, waxing gibbous, full, waning gibbous, last quarter,
//! waning crescent - see [`DayNightClock::moon_phase`]), one per full
//! day/night cycle, the same 8-phase-per-day convention Minecraft uses.
//! Each phase is a separately masked copy of the *same* base moon
//! texture (procedural or `moon.png`) - see [`moon_lit`] - rather than 8
//! independent images, so a custom `moon.png` override automatically gets
//! correct phase shapes with no extra files needed.
//!
//! Full moons also get an occasional special color, purely cosmetic for now
//! (no gameplay effect - see [`DayNightClock::moon_event`]): a **red moon**
//! twice a year, a **blue moon** once a year in [`Season::Summer`] (never
//! [`Season::Winter`]), and a **green moon** once a year in
//! [`Season::Autumn`] (never [`Season::Spring`]). Which month(s) each
//! lands on is re-rolled every year (seeded, not truly random - see
//! [`year_schedule`]), never the same month as another event that year and
//! never immediately next to one either - there's always at least one
//! plain-moon month of breathing room between any two specials, so a
//! blue/red/green chain can never land three months in a row. Each is a
//! plain color tint multiplied into the moon's existing texture
//! (`update_sky`), not a separate sprite.
//!
//! All of that - frequency, excluded seasons, whether an event even needs
//! a full moon, whether it needs a gap month - lives in one declarative
//! table ([`MOON_EVENTS`]), not per-event code: adding a fourth event, or
//! changing an existing one's frequency/season/gap rule, means editing
//! that table. [`Season`] itself is a pure calendar concept with no other
//! effect yet - it exists solely to make the excluded-season rules real
//! and checkable instead of a permanent no-op.
//!
//! The clock (and moon phase) persists per-world (`save::WorldData
//! ::time_of_day`/`::day_count`) so leaving and reloading resumes rather
//! than resetting to dawn/new-moon - the same
//! don't-silently-lose-continuous-state-on-reload lesson as fluids (see
//! CLAUDE.md).

